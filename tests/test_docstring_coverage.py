"""Prevent undocumented public Python symbols from entering the benchmark."""

from __future__ import annotations

import ast
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FIRST_PARTY_DIRS = (
    "powerbench",
    "analysis",
    "benchmark",
    "experiments",
    "models",
    "scripts",
)


def python_sources() -> list[Path]:
    """Return every maintained first-party Python source file.
    
    Returns:
        list[Path]: Sorted source paths excluding generated bytecode directories.
    """
    return sorted(
        path
        for directory in FIRST_PARTY_DIRS
        for path in (ROOT / directory).rglob("*.py")
        if "__pycache__" not in path.parts
    )


class DocstringCoverageTests(unittest.TestCase):
    """Enforce source-level documentation for public Python definitions.
    
    Bases:
        unittest.TestCase
    """

    def test_every_public_python_definition_has_a_docstring(self) -> None:
        """Require module and public-symbol documentation across first-party code.
        
        Returns:
            None; assertions report every missing documentation contract together.
        """
        failures: list[str] = []
        for path in python_sources():
            relative = path.relative_to(ROOT)
            tree = ast.parse(path.read_text(), filename=str(relative))
            parents = {
                child: parent
                for parent in ast.walk(tree)
                for child in ast.iter_child_nodes(parent)
            }
            if not ast.get_docstring(tree):
                failures.append(f"{relative}: module docstring missing")
            for node in ast.walk(tree):
                if not isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                    continue
                if node.name.startswith("_"):
                    continue
                parent = parents.get(node)
                if isinstance(parent, ast.ClassDef) and parent.name.startswith("_"):
                    continue
                doc = ast.get_docstring(node) or ""
                location = f"{relative}:{node.lineno} {node.name}"
                if not doc:
                    failures.append(f"{location}: definition docstring missing")
                    continue
        self.assertFalse(failures, "\n" + "\n".join(failures))
